"""Minimal OpenFOAM (ESI/OpenCFD v2xxx, tested syntax target v2512) dictionary writers."""
from __future__ import annotations

from pathlib import Path

OF_VERSION = "v2512"

_HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  generated by flexblade.cfd — OpenFOAM {ver} (ESI) syntax
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    location    "{loc}";
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def fmt(v) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.10g}"
    if isinstance(v, (tuple, list)) and all(isinstance(x, (int, float)) for x in v):
        return "(" + " ".join(fmt(float(x)) for x in v) + ")"
    return str(v)


def dict_body(d: dict, indent: int = 0) -> str:
    pad = "    " * indent
    out = []
    for k, v in d.items():
        if isinstance(v, dict):
            out.append(f"{pad}{k}\n{pad}{{\n{dict_body(v, indent + 1)}{pad}}}\n")
        elif isinstance(v, RawEntry):
            out.append(f"{pad}{k} {v.text};\n" if k else f"{pad}{v.text}\n")
        else:
            out.append(f"{pad}{k:<15} {fmt(v)};\n")
    return "".join(out)


class RawEntry:
    def __init__(self, text: str):
        self.text = text


def write_dict(case: Path, rel: str, body: dict | str, cls: str = "dictionary") -> Path:
    p = Path(case) / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    obj = p.name
    loc = str(Path(rel).parent)
    text = _HEADER.format(ver=OF_VERSION, cls=cls, loc=loc, obj=obj)
    text += body if isinstance(body, str) else dict_body(body)
    text += "\n// ************************************************************************* //\n"
    p.write_text(text)
    return p


def field_file(case: Path, name: str, cls: str, dims: str, internal: str,
               patches: dict[str, dict]) -> Path:
    body = f"dimensions      {dims};\n\ninternalField   {internal};\n\nboundaryField\n{{\n"
    for pname, d in patches.items():
        body += f"    {pname}\n    {{\n" + dict_body(d, 2) + "    }\n"
    body += "}\n"
    return write_dict(case, f"0/{name}", body, cls)


def write_allrun(case: Path, lines: list[str]) -> Path:
    p = Path(case) / "Allrun"
    p.write_text("#!/bin/bash\n# generated by flexblade.cfd; usage: ./Allrun [nprocs]\n"
                 "cd \"${0%/*}\" || exit 1\nNP=${1:-1}\nset -o pipefail\n"
                 "run() { echo \"== $*\"; \"$@\" > log.$(basename $1) 2>&1 || "
                 "{ echo \"FAILED: $*\"; tail -30 log.$(basename $1); exit 1; }; }\n"
                 "runp() { app=$1; shift; if [ \"$NP\" -gt 1 ]; then echo \"== mpirun -np $NP $app\"; "
                 "mpirun ${MPIRUN_FLAGS:-} -np $NP $app -parallel \"$@\" > log.$app 2>&1 || "
                 "{ echo \"FAILED: $app\"; tail -30 log.$app; exit 1; }; else run $app \"$@\"; fi; }\n"
                 + "\n".join(lines) + "\n")
    p.chmod(0o755)
    return p


def decompose_dict(case: Path, np_: int) -> Path:
    return write_dict(case, "system/decomposeParDict",
                      {"numberOfSubdomains": int(max(np_, 1)), "method": "scotch"})


def turbulence_fields_kw(model: str, U: float, L: float, intensity: float = 0.001,
                         visc_ratio: float = 1.0, nu: float = 1.5e-5):
    """Freestream k, omega for SST (low turbulence)."""
    k = 1.5 * (U * intensity) ** 2
    omega = k / (visc_ratio * nu)
    return k, omega
