"""Real filament / insert database: datasheet records → simulator `Material`s.

Data file: ``flexblade/data/filaments.json`` (installed as package data). It is a
JSON object ``{"schema_version", "generated", "fx_to_usd", "entries": [...]}``; each
entry is one product and has two layers:

1. **Datasheet layer** — exactly what the manufacturer published, never invented:

   ``name`` (unique snake_case id, also the material name in designs),
   ``brand``, ``product``, ``class`` (see `CLASSES`), ``url`` (purchase page),
   ``tds_url``, ``price`` {value, currency, per_kg, spool_kg, date, store, note},
   ``tds`` {density_g_cm3, tensile_modulus_xy_MPa, tensile_strength_xy_MPa,
   elongation_xy_pct, *_z_* counterparts, flexural_modulus/strength xy/z,
   shore_hardness, hdt_C, hdt_load_MPa, impact_*, test_standard, specimen,
   specimen_notes, conditioning, conditioned{…same keys…}, inserts: rod_modulus_GPa,
   fibre_modulus_GPa, diameters_mm}, ``print`` {nozzle/bed temps,
   hardened_nozzle_required, ams_compatible, drying, moisture_sensitivity},
   ``confidence`` (high | medium | low) and ``notes``.  Missing values are null.

2. **Simulator layer** — ``sim`` {rho, E1, E2, E3, G12, G13, G23, nu12, nu13, nu23,
   loss_factor, freq_scale, freq_loss, Xt, Yt, Zt, S, creep_strain_allow,
   fatigue_strain_amp_allow, fatigue_stress_ratio, is_elastomer} in SI, generated by
   `derive()` from the datasheet layer, plus ``derived`` {field: rule} naming the
   rule for every simulator field that is *not* a direct datasheet value (fields
   taken straight from the TDS are listed as ``"tds:<key>"``).

`JSON_SCHEMA` below is the machine-readable schema (draft 2020-12) of one entry;
tests validate the file against its required keys and value ranges.

Derivation rules (all documented per field in the data file)
-------------------------------------------------------------
* Axis 1 (raster) modulus/strength = TDS "XY" (flat-printed) tensile values. Many
  TDSs print XY bars with ±45° or concentric rasters, so for fibre-filled grades E1
  is, if anything, *under*-estimated. Flexural modulus is used when no tensile
  modulus is given (``E1 = flexural`` — conservative for elastomers, about equal for
  rigid polymers).
* Axis 3 (interlayer, Z) = TDS Z value when given (Prusament's "interlayer adhesion"
  counts as Z strength), else ``XY × class ratio``. The class ratio is the **median over
  the database's own datasheets that publish both Z and XY** when ≥ 3 do
  (`class_ratios()`; e.g. pa_cf E 0.54 / σ 0.52 from 8 TDSs, tpu 0.83 / 0.65 from 8,
  petg 0.88 / 0.86 from 6), else the family default (unfilled E 0.87 / σ 0.70, nylon
  σ 0.45, short-CF 0.50 / 0.45, GF 0.65 / 0.50, elastomer 0.83 / 0.65 — the medians of
  the families). Published Z bars are best-case (dried, often annealed, ideal
  settings): real parts are usually weaker in Z.
* Axis 2 (in-layer transverse) = XY × class ratio (unfilled 0.9, fibre-filled
  0.45–0.6) — almost never published.
* Shear moduli from the orthotropic estimate G_ij = E_j / (2(1+ν)) (same as the
  generic `_fdm` helper); S (shear strength) = 0.9 × min(Yt, Zt).
* TPU / TPE without any modulus: E1 from Shore hardness via a log-linear fit
  through the entries of the database that publish both hardness and modulus
  (`shore_modulus_fit`). Storage modulus vs frequency and loss use the generic TPU
  DMA table (`materials._TPU_F`, `_TPU_LOSS`).
* Density missing → class default (`rho`), flagged.
* creep_strain_allow — sustained strain over the design life at 25 °C. Not a
  datasheet quantity anywhere; class table (TPU by hardness: ≤87A 3 %, ≤92A 2.5 %,
  ≤96A 2 %, ≤98A 1.8 %, D-scale 1.5 %; rigid polymers 0.3–1 %, e.g. PLA 0.3 %,
  PETG 0.4 %, ABS/ASA 0.5 %, PC/PA 0.6 %, short-CF 0.3–0.4 %), additionally capped
  at 0.25 × elongation-at-break for brittle grades. Order-of-magnitude design
  guidance (long-term permissible strain ≈ ½–⅓ of short-term permissible strain for
  thermoplastics); treat as LOW confidence for every brand.
* fatigue_stress_ratio — class table (0.25 PLA/PETG/ABS/PC, 0.3 PA/PP/fibre-filled,
  0.35 PEEK/metals/rods). fatigue_strain_amp_allow = ratio × Xt / E1 for rigid
  materials (consistent with the stress criterion); elastomers by hardness
  (85A 4 %, 90A 3.5 %, 95A 3 %, 98A 2.5 %, D 2 %).
* Nylons: TDS "dry" values are used for the main entry; when the TDS also gives
  conditioned (50 % RH) values a second material ``<name>_cond`` is registered.
"""
