# --------------------------------------------------------------------------- helpers

def _num(x) -> float | None:
    if x is None or isinstance(x, bool):
        return None
    if isinstance(x, (int, float)):
        return float(x) if math.isfinite(float(x)) else None
    m = re.search(r"-?\d+(\.\d+)?", str(x))
    return float(m.group()) if m else None


def shore_value(s) -> tuple[float, str] | None:
    """'95A' -> (95, 'A'); '64D' -> (64, 'D'); None if unparsable."""
    if s is None:
        return None
    m = re.search(r"(\d+(?:\.\d+)?)\s*(?:shore\s*)?([AD])", str(s), re.I) or \
        re.search(r"shore\s*([AD])\D*(\d+(?:\.\d+)?)", str(s), re.I)
    if not m:
        return None
    a, b = m.groups()
    return (float(a), b.upper()) if a[0].isdigit() else (float(b), a.upper())


def shore_index(s) -> float | None:
    """Single hardness axis: Shore A value, D mapped by D ≈ A − 50 above 90A (D40≈A90,
    D64≈A98+) — monotone ordering only."""
    v = shore_value(s)
    if v is None:
        return None
    return v[0] if v[1] == "A" else 50.0 + v[0]


def _tds(rec, key):
    return _num((rec.get("tds") or {}).get(key))


def usd_per_kg(price: dict | None, fx: dict = FX_TO_USD) -> float | None:
    if not price or price.get("value") in (None, 0) or not price.get("per_kg", True):
        return None
    rate = fx.get(str(price.get("currency", "USD")).upper())
    return None if rate is None else round(float(price["value"]) * rate, 2)


# --------------------------------------------------------------------------- derivation

def shore_modulus_fit(records: list[dict]) -> tuple[float, float, int]:
    """Least-squares log10(E_MPa) = a + b·shore_index over elastomer records that publish
    both hardness and a (tensile or flexural) modulus. Returns (a, b, n)."""
    xs, ys = [], []
    for r in records:
        if not CLASSES.get(r.get("class"), {}).get("elastomer"):
            continue
        h = shore_index((r.get("tds") or {}).get("shore_hardness"))
        E = _tds(r, "tensile_modulus_xy_MPa") or _tds(r, "flexural_modulus_xy_MPa")
        if h is not None and E and E > 0:
            xs.append(h)
            ys.append(math.log10(E))
    pts = list(zip(xs, ys))
    fit = (math.log10(26.0) - 0.06 * 95, 0.06, len(pts))   # fallback through generic 95A=26 MPa
    for _ in range(3):   # least squares with outlier rejection (> factor OUTLIER off the fit)
        n = len(pts)
        if n < 3:
            break
        mx, my = sum(p[0] for p in pts) / n, sum(p[1] for p in pts) / n
        sxx = sum((x - mx) ** 2 for x, _ in pts)
        b = sum((x - mx) * (y - my) for x, y in pts) / sxx if sxx > 0 else 0.06
        fit = (my - b * mx, b, n)
        keep = [(x, y) for x, y in pts if abs(y - (fit[0] + b * x)) <= math.log10(OUTLIER)]
        if len(keep) == len(pts):
            break
        pts = keep
    return fit


OUTLIER = 2.5   # elastomer TDS modulus further than this factor from the hardness fit is flagged


def _elastomer_tables(h: float | None) -> tuple[float, float, str]:
    """(creep allow, fatigue strain amp) by hardness index."""
    if h is None:
        return 0.02, 0.03, "hardness unknown → 95A class"
    if h <= 87:
        return 0.03, 0.04, "≤87A class"
    if h <= 92:
        return 0.025, 0.035, "≤92A class"
    if h <= 96:
        return 0.02, 0.03, "≤96A class"
    if h <= 99.5:
        return 0.018, 0.025, "≤98A class"
    return 0.015, 0.02, "Shore D class"


MIN_EVIDENCE = 3


def class_ratios(records: list[dict]) -> dict[str, dict[str, Any]]:
    """Per-class median Z/XY modulus and strength ratios over records that publish both
    (used instead of the family default when ≥ MIN_EVIDENCE publishers)."""
    import statistics
    out: dict[str, dict[str, Any]] = {}
    for c, v in class_ratio_evidence(records).items():
        d: dict[str, Any] = {}
        if len(v["E_z/E_xy"]) >= MIN_EVIDENCE:
            d["e3"] = round(min(1.0, statistics.median(v["E_z/E_xy"])), 3)
            d["n_e3"] = len(v["E_z/E_xy"])
        if len(v["S_z/S_xy"]) >= MIN_EVIDENCE:
            d["zt"] = round(min(1.0, statistics.median(v["S_z/S_xy"])), 3)
            d["n_zt"] = len(v["S_z/S_xy"])
        if d:
            out[c] = d
    return out


def _frac(v: float) -> float:
    """Strain given in percent (> 0.2) -> fraction."""
    return v / 100.0 if v > 0.2 else v


def class_literature(lit: dict[str, list[dict]], records: list[dict]) -> dict[str, dict]:
    """Literature fatigue/creep findings per class -> {cls: {"fr": (ratio, rule),
    "creep": (strain, rule), "eps_f": (strain, rule)}}. Medians; FDM-printed findings are
    preferred over moulded when both exist. fatigue_strength_MPa is converted to a ratio
    with the class median TDS tensile strength."""
    import statistics
    out: dict[str, dict] = {}
    uts: dict[str, list[float]] = {}
    for r in records:
        v = _tds(r, "tensile_strength_xy_MPa")
        if v:
            uts.setdefault(r["class"], []).append(v)
    for cls, finds in lit.items():
        if cls.startswith("_") or not isinstance(finds, list):
            continue
        targets = [c for c in re.split(r"[/,+ ]+", cls) if c in CLASSES]
        for c in targets:
            d: dict = {}

            def pick(q):
                f = [x for x in finds if x.get("quantity") == q and _num(x.get("value")) is not None]
                pr = [x for x in f if "print" in str(x.get("specimen", "")).lower() or "fdm" in str(x.get("specimen", "")).lower()]
                return pr or f

            def cite(fs):
                return "; ".join(sorted({str(x.get("source", "?"))[:80] for x in fs}))[:300]
            rat = pick("fatigue_ratio")
            fs = pick("fatigue_strength_MPa")
            if rat:
                d["fr"] = (min(1.0, statistics.median(_num(x["value"]) for x in rat)),
                           f"literature median fatigue/UTS over {len(rat)} findings ({cite(rat)})")
            elif fs and uts.get(c):
                u = statistics.median(uts[c])
                v = statistics.median(_num(x["value"]) for x in fs)
                d["fr"] = (min(1.0, v / u), f"literature fatigue strength {v:g} MPa (median of {len(fs)}: "
                           f"{cite(fs)}) / class median TDS UTS {u:g} MPa")
            cr = pick("creep_strain_allow")
            if cr:
                d["creep"] = (statistics.median(_frac(_num(x["value"])) for x in cr),
                              f"literature permissible long-term strain, median of {len(cr)} ({cite(cr)})")
            ef = pick("fatigue_strain_amp")
            if ef:
                d["eps_f"] = (statistics.median(_frac(_num(x["value"])) for x in ef),
                              f"literature fatigue strain amplitude, median of {len(ef)} ({cite(ef)})")
            if d:
                out.setdefault(c, {}).update(d)
    return out


def derive(rec: dict, fit: tuple[float, float, int] | None = None,
           conditioned: bool = False, ratios: dict | None = None,
           lit: dict | None = None) -> tuple[dict, dict]:
    """Datasheet record -> (sim dict SI, derived {field: rule}). `ratios` = class_ratios()."""
    cls = rec["class"]
    C = dict(CLASSES[cls])
    ev = (ratios or {}).get(cls, {})
    for k in ("e3", "zt"):
        if k in ev:
            C[k] = ev[k]
            C[f"src_{k}"] = f"median of {ev['n_' + k]} DB {cls} datasheets publishing Z and XY"
        else:
            C[f"src_{k}"] = "family default (fewer than 3 datasheets in class publish Z and XY)"
    tds = dict(rec.get("tds") or {})
    if conditioned:
        for k, v in (tds.get("conditioned") or {}).items():
            if v is not None:
                tds[k] = v
    g = lambda k: _num(tds.get(k))  # noqa: E731
    D: dict[str, str] = {}
    sim: dict[str, Any] = {}
    insert = cls in INSERT_CLASSES
    elast = bool(C.get("elastomer"))

    # density
    if g("density_g_cm3"):
        sim["rho"] = g("density_g_cm3") * 1000.0
        D["rho"] = "tds:density_g_cm3"
    else:
        sim["rho"] = float(C["rho"])
        D["rho"] = f"class default {C['rho']} kg/m3 ({cls}); TDS gives no density"

    # axis-1 modulus
    if insert:
        E = g("rod_modulus_GPa")
        if E:
            sim["E1"], D["E1"] = E * 1e9, "tds:rod_modulus_GPa"
        elif g("tensile_modulus_xy_MPa"):
            sim["E1"], D["E1"] = g("tensile_modulus_xy_MPa") * 1e6, "tds:tensile_modulus_xy_MPa"
        elif g("flexural_modulus_xy_MPa"):
            sim["E1"], D["E1"] = g("flexural_modulus_xy_MPa") * 1e6, "tds:flexural_modulus_xy_MPa"
        else:
            ref = {"cf_rod": 125e9, "cf_continuous": 60e9, "gf_rod": 40e9,
                   "steel_wire": 193e9, "nitinol": 60e9}[cls]
            sim["E1"] = ref
            D["E1"] = f"class reference {ref/1e9:g} GPa ({cls}); seller states no modulus"
    else:
        if g("tensile_modulus_xy_MPa"):
            sim["E1"], D["E1"] = g("tensile_modulus_xy_MPa") * 1e6, "tds:tensile_modulus_xy_MPa"
        elif g("flexural_modulus_xy_MPa"):
            sim["E1"] = g("flexural_modulus_xy_MPa") * 1e6
            D["E1"] = "tds:flexural_modulus_xy_MPa (no tensile modulus given; E1 = flexural)"
        elif elast and shore_index(tds.get("shore_hardness")) is not None:
            a, b, n = fit or (math.log10(26.0) - 0.06 * 95, 0.06, 0)
            h = shore_index(tds.get("shore_hardness"))
            sim["E1"] = 10 ** (a + b * h) * 1e6
            D["E1"] = (f"Shore→modulus log-linear fit over {n} DB elastomers "
                       f"(log10 E_MPa = {a:.3f} + {b:.4f}·H, H={h:g}); no modulus in TDS")
        elif g("tensile_modulus_z_MPa"):
            sim["E1"] = g("tensile_modulus_z_MPa") * 1e6 / C["e3"]
            D["E1"] = f"Z modulus / class ratio {C['e3']} (only Z given)"
        else:
            raise ValueError(f"{rec['name']}: no modulus or hardness — cannot derive E1")
        # elastomer plausibility: TDS modulus vs hardness fit (vendors differ in strain range /
        # rate; a few report secant or 'Young's' values 3-5x off their own hardness class)
        h = shore_index(tds.get("shore_hardness"))
        # (Shore A grades only: D-scale grades are few and hardness predicts modulus poorly there)
        if elast and h is not None and h <= 100 and D["E1"].startswith("tds:") and fit is not None:
            a, b, n = fit
            Efit = 10 ** (a + b * h) * 1e6
            if not (1 / OUTLIER <= sim["E1"] / Efit <= OUTLIER):
                D["E1"] = (f"TDS modulus {sim['E1']/1e6:g} MPa is {sim['E1']/Efit:.2f}× the Shore-hardness "
                           f"fit over {n} DB elastomers ({Efit/1e6:.3g} MPa at H={h:g}) — outside "
                           f"×/÷{OUTLIER}, treated as a different test definition; E1 = fit value "
                           "(verify with a coupon / DMA)")
                ez = g("tensile_modulus_z_MPa")
                sim["E1"] = Efit
                if ez:
                    tds["_ez_ratio"] = ez / g("tensile_modulus_xy_MPa")

    E1 = sim["E1"]
    if insert:
        if cls in ("steel_wire", "nitinol"):
            sim["E2"] = sim["E3"] = E1
            D["E2"] = D["E3"] = "isotropic metal"
        else:
            ET = {"cf_rod": 8e9, "cf_continuous": 4e9, "gf_rod": 10e9}[cls]
            sim["E2"] = sim["E3"] = ET
            D["E2"] = D["E3"] = (f"unidirectional composite transverse modulus ≈ {ET/1e9:g} GPa "
                                 "(matrix-dominated, generic UD epoxy/nylon value)")
    else:
        sim["E2"] = E1 * C["e2"]
        D["E2"] = f"E1 × {C['e2']} (in-layer transverse, class {cls}; never published)"
        if g("tensile_modulus_z_MPa") and D["E1"].startswith("tds:tensile"):
            sim["E3"], D["E3"] = g("tensile_modulus_z_MPa") * 1e6, "tds:tensile_modulus_z_MPa"
        elif tds.get("_ez_ratio"):
            r = min(1.0, tds["_ez_ratio"])
            sim["E3"] = E1 * r
            D["E3"] = f"E1 × TDS Z/XY modulus ratio {r:.3f}"
        elif g("flexural_modulus_z_MPa") and g("flexural_modulus_xy_MPa"):
            r = g("flexural_modulus_z_MPa") / g("flexural_modulus_xy_MPa")
            sim["E3"] = E1 * r
            D["E3"] = f"E1 × flexural Z/XY ratio {r:.3f} (tds:flexural_modulus_z/xy)"
        else:
            sim["E3"] = E1 * C["e3"]
            D["E3"] = f"E1 × {C['e3']} (interlayer ratio: {C['src_e3']}; TDS has no Z modulus)"
        sim["E3"] = min(sim["E3"], E1)   # Z never stiffer than raster in this model

    nu = C["nu"]
    sim["nu12"] = sim["nu13"] = nu
    sim["nu23"] = 0.4 if cls in ("cf_rod", "cf_continuous", "gf_rod") else nu
    D["nu12"] = D["nu13"] = D["nu23"] = f"class default ν={nu}"
    if insert and cls in ("steel_wire", "nitinol"):
        G = E1 / (2 * (1 + nu))
        sim["G12"] = sim["G13"] = sim["G23"] = G
        D["G12"] = D["G13"] = D["G23"] = "E/(2(1+ν)) isotropic"
    elif insert:
        GT = {"cf_rod": (4.5e9, 3e9), "cf_continuous": (2.5e9, 1.5e9), "gf_rod": (4.5e9, 3.5e9)}[cls]
        sim["G12"] = sim["G13"] = GT[0]
        sim["G23"] = GT[1]
        D["G12"] = D["G13"] = D["G23"] = "generic UD composite shear moduli (matrix-dominated)"
    else:
        sim["G12"] = sim["E2"] / (2 * (1 + nu))
        sim["G13"] = sim["G23"] = sim["E3"] / (2 * (1 + nu))
        D["G12"] = D["G13"] = D["G23"] = "orthotropic estimate G_ij = E_j/(2(1+ν)) (as materials._fdm)"

    # strengths
    Xt = g("tensile_strength_xy_MPa") or g("tensile_strength_MPa")
    if Xt:
        sim["Xt"], D["Xt"] = Xt * 1e6, "tds:tensile_strength_xy_MPa"
    elif g("tensile_strength_z_MPa"):
        zt = C.get("zt", 0.6)
        sim["Xt"] = g("tensile_strength_z_MPa") * 1e6 / zt
        D["Xt"] = f"Z strength / class ratio {zt}"
    elif g("flexural_strength_xy_MPa"):
        sim["Xt"] = 0.6 * g("flexural_strength_xy_MPa") * 1e6
        D["Xt"] = "0.6 × flexural strength (tensile not given; flexural/tensile ≈ 1.5–1.8 for printed polymers)"
    elif elast and (g("stress_at_100pct_MPa") or g("stress_at_50pct_MPa")):
        k = "stress_at_100pct_MPa" if g("stress_at_100pct_MPa") else "stress_at_50pct_MPa"
        sim["Xt"] = g(k) * 1e6
        D["Xt"] = f"lower bound = tds:{k} (no tensile strength in TDS; strength ≥ stress at that elongation)"
    else:
        ref = {"cf_rod": 1500e6, "cf_continuous": 600e6, "gf_rod": 700e6,
               "steel_wire": 1300e6, "nitinol": 1000e6}.get(cls)
        if ref is None:
            raise ValueError(f"{rec['name']}: no strength — cannot derive Xt")
        sim["Xt"] = ref
        D["Xt"] = f"class reference {ref/1e6:g} MPa (seller gives no strength)"
    if insert:
        if cls in ("steel_wire", "nitinol"):
            sim["Yt"] = sim["Zt"] = sim["Xt"]
            sim["S"] = 0.55 * sim["Xt"]
            D["Yt"] = D["Zt"] = "isotropic metal"
            D["S"] = "0.55 × Xt (torsional / tensile strength of spring wire ≈ 0.5–0.6)"
        else:
            T = {"cf_rod": (50e6, 60e6), "cf_continuous": (30e6, 40e6), "gf_rod": (45e6, 55e6)}[cls]
            sim["Yt"] = sim["Zt"] = T[0]
            sim["S"] = T[1]
            D["Yt"] = D["Zt"] = D["S"] = "generic UD composite transverse / shear strength"
    else:
        sim["Yt"] = sim["Xt"] * C["yt"]
        D["Yt"] = f"Xt × {C['yt']} (in-layer transverse, class {cls})"
        if g("tensile_strength_z_MPa") and D["Xt"].startswith("tds:"):
            sim["Zt"], D["Zt"] = min(g("tensile_strength_z_MPa") * 1e6, sim["Xt"]), "tds:tensile_strength_z_MPa"
        elif g("interlayer_adhesion_MPa") and D["Xt"].startswith("tds:"):
            sim["Zt"] = min(g("interlayer_adhesion_MPa") * 1e6, sim["Xt"])
            D["Zt"] = "tds:interlayer_adhesion_MPa (Prusament interlayer adhesion test)"
        elif g("flexural_strength_z_MPa") and g("flexural_strength_xy_MPa"):
            r = min(1.0, g("flexural_strength_z_MPa") / g("flexural_strength_xy_MPa"))
            sim["Zt"] = sim["Xt"] * r
            D["Zt"] = f"Xt × flexural strength Z/XY ratio {r:.3f}"
        else:
            sim["Zt"] = sim["Xt"] * C["zt"]
            D["Zt"] = f"Xt × {C['zt']} (interlayer strength ratio: {C['src_zt']}; no Z strength in TDS)"
        sim["S"] = 0.9 * min(sim["Yt"], sim["Zt"])
        D["S"] = "0.9 × min(Yt, Zt) (no shear strength published)"

    # damping / frequency
    sim["loss_factor"] = C["loss"]
    sim["freq_scale"] = [list(p) for p in C["fs"]]
    sim["freq_loss"] = [list(p) for p in C.get("fl", ())]
    D["loss_factor"] = D["freq_scale"] = (
        "generic TPU DMA table (materials._TPU_F/_TPU_LOSS)" if elast
        else f"class default η={C['loss']} (no DMA data published)")

    # allowables
    h = shore_index(tds.get("shore_hardness"))
    L = (lit or {}).get(cls, {})
    fr = C["fr"]
    D["fatigue_stress_ratio"] = f"class table {fr} (fatigue strength at 1e7 / static)"
    if g("fatigue_strength_MPa") and D["Xt"].startswith("tds:"):
        fr = min(1.0, g("fatigue_strength_MPa") * 1e6 / sim["Xt"])
        D["fatigue_stress_ratio"] = "tds:fatigue_strength_MPa / Xt"
    elif "fr" in L:
        fr, D["fatigue_stress_ratio"] = L["fr"]
    sim["fatigue_stress_ratio"] = fr
    if elast:
        cr, fa, why = _elastomer_tables(h)
        D["creep_strain_allow"] = f"elastomer hardness table {cr:g} ({why})"
        D["fatigue_strain_amp_allow"] = f"elastomer hardness table {fa:g} ({why})"
        if "creep" in L:
            cr, D["creep_strain_allow"] = L["creep"]
        if "eps_f" in L:
            fa, D["fatigue_strain_amp_allow"] = L["eps_f"]
        # stress consistency (bites only for stiff D-scale grades): fatigue stress amplitude
        # ≤ fr·Xt, sustained stress ≤ 0.5·Xt
        if fr * sim["Xt"] / E1 < fa:
            fa = fr * sim["Xt"] / E1
            D["fatigue_strain_amp_allow"] += f"; capped at fatigue_stress_ratio × Xt/E1 = {fa:.4g}"
        if 0.5 * sim["Xt"] / E1 < cr:
            cr = 0.5 * sim["Xt"] / E1
            D["creep_strain_allow"] += f"; capped at 0.5 × Xt/E1 = {cr:.4g} (sustained stress ≤ ½ UTS)"
        sim["creep_strain_allow"] = cr
        sim["fatigue_strain_amp_allow"] = fa
    else:
        cr = C["creep"]
        why = f"class table {cr:g} ({cls})"
        if "creep" in L:
            cr, why = L["creep"]
        el = g("elongation_xy_pct")
        if el and not insert and 0.25 * el / 100 < cr:
            cr = 0.25 * el / 100
            why += f", capped 0.25 × elongation {el:g} %"
        if not insert and 0.5 * sim["Xt"] / E1 < cr:
            cr = 0.5 * sim["Xt"] / E1
            why += f", capped 0.5 × Xt/E1 = {cr:.4g} (sustained stress ≤ ½ UTS)"
        sim["creep_strain_allow"] = cr
        D["creep_strain_allow"] = why
        sim["fatigue_strain_amp_allow"] = fr * sim["Xt"] / E1
        D["fatigue_strain_amp_allow"] = f"fatigue_stress_ratio × Xt / E1 = {fr} × Xt/E1"
    sim["is_elastomer"] = elast
    D["is_elastomer"] = f"class {cls}"
    for k, v in list(sim.items()):
        if isinstance(v, float):
            sim[k] = float(f"{v:.6g}")
    return sim, D


def build_entries(records: list[dict], fx: dict = FX_TO_USD,
                  literature: dict | None = None) -> list[dict]:
    """Raw research records -> database entries (adds sim/derived, usd price, _cond variants).
    literature: {class: [findings]} fatigue/creep literature (see class_literature)."""
    fit = shore_modulus_fit(records)
    ratios = class_ratios(records)
    lit = class_literature(literature or {}, records)
    out, seen = [], set()
    for r in records:
        r = json.loads(json.dumps(r))
        if r["name"] in seen:
            raise ValueError(f"duplicate name {r['name']}")
        seen.add(r["name"])
        for k in ("url", "tds_url"):
            if r.get(k):
                r[k] = quote(r[k].strip(), safe=":/?&=%#+@,;~!$'()*[]")
        if r.get("price"):
            r["price"]["usd_per_kg"] = usd_per_kg(r["price"], fx)
        r["sim"], r["derived"] = derive(r, fit, ratios=ratios, lit=lit)
        out.append(r)
        cond = (r.get("tds") or {}).get("conditioned")
        if cond and any(v is not None for k, v in cond.items() if k.endswith("_MPa")):
            v = json.loads(json.dumps(r))
            metal = r["class"] in ("steel_wire", "nitinol")
            v["name"] = r["name"] + ("_aged" if metal else "_cond")
            v["product"] = r["product"] + (" (aged)" if metal else " (conditioned)")
            v["variant_of"] = r["name"]
            v["sim"], v["derived"] = derive(r, fit, conditioned=True, ratios=ratios, lit=lit)
            v["derived"] = {k: (d + " [conditioned values]" if d.startswith("tds:") else d)
                            for k, d in v["derived"].items()}
            out.append(v)
    return out


def class_ratio_evidence(entries: list[dict]) -> dict[str, dict[str, list[float]]]:
    """Z/XY modulus and strength ratios published per class (to check CLASSES e3/zt)."""
    ev: dict[str, dict[str, list[float]]] = {}
    for e in entries:
        if e.get("variant_of"):
            continue
        t = e.get("tds") or {}
        c = ev.setdefault(e["class"], {"E_z/E_xy": [], "S_z/S_xy": []})
        a, b = _num(t.get("tensile_modulus_z_MPa")), _num(t.get("tensile_modulus_xy_MPa"))
        if a and b:
            c["E_z/E_xy"].append(round(a / b, 3))
        a, b = _num(t.get("tensile_strength_z_MPa")), _num(t.get("tensile_strength_xy_MPa"))
        if a and b:
            c["S_z/S_xy"].append(round(a / b, 3))
    return {k: v for k, v in ev.items() if v["E_z/E_xy"] or v["S_z/S_xy"]}


def load_entries(path: Path | str = DATA_PATH) -> list[dict]:
    p = Path(path)
    if not p.exists():
        return []
    return json.loads(p.read_text())["entries"]


def write_db(entries: list[dict], path: Path | str = DATA_PATH) -> None:
    import datetime as _dt
    doc = {"schema_version": SCHEMA_VERSION,
           "generated": _dt.date.today().isoformat(),
           "fx_to_usd": FX_TO_USD,
           "description": "Real filament/insert datasheet values (tds) + derived simulator "
                          "properties (sim, derived). See flexblade/filament_db.py.",
           "json_schema": JSON_SCHEMA,
           "entries": entries}
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")


def dedupe(recs: list[dict]) -> list[dict]:
    """Same name researched twice: keep the record with more non-null numeric TDS values."""
    def score(r):
        return sum(isinstance(v, (int, float)) and not isinstance(v, bool)
                   for v in (r.get("tds") or {}).values())
    best: dict[str, dict] = {}
    for r in recs:
        o = best.get(r["name"])
        if o is None or score(r) > score(o):
            best[r["name"]] = r
    return [r for r in recs if best[r["name"]] is r]


def apply_overlays(recs: list[dict], overlays: list[dict]) -> list[dict]:
    """Overlay files: {name: {"price": {...}, "url": str|None, "set": {dotted.key: value},
    "drop": bool}} — price lookups and manual corrections made after the datasheet
    research (each correction should say why in "note", appended to the record notes)."""
    by = {r["name"]: r for r in recs}
    for ov in overlays:
        for name, o in ov.items():
            if name.startswith("_"):
                continue
            r = by.get(name)
            if r is None:
                continue
            if o.get("drop"):
                by.pop(name)
                continue
            if o.get("price") and (not r.get("price") or r["price"].get("value") is None):
                r["price"] = o["price"]
            if o.get("url"):
                r["url"] = o["url"]
            for k, v in (o.get("set") or {}).items():
                tgt = r
                parts = k.split(".")
                for p in parts[:-1]:
                    tgt = tgt.setdefault(p, {}) if tgt.get(p) is not None else tgt.setdefault(p, {}) or tgt[p]
                    if tgt is None:
                        break
                tgt[parts[-1]] = v
            if o.get("note"):
                r["notes"] = ((r.get("notes") or "") + " [db fix: " + o["note"] + "]").strip()
    return [r for r in recs if r["name"] in by]


def main(argv: list[str] | None = None) -> None:
    """python -m flexblade.filament_db raw1.json ... [overlay.json ...] [-o data/filaments.json]
    Arrays are research record files; objects are overlays (see apply_overlays)."""
    import argparse
    ap = argparse.ArgumentParser(description=main.__doc__)
    ap.add_argument("raw", nargs="+")
    ap.add_argument("-o", "--out", default=str(DATA_PATH))
    a = ap.parse_args(argv)
    recs, overlays, literature = [], [], {}
    for f in a.raw:
        doc = json.loads(Path(f).read_text())
        if Path(f).name.startswith("fatigue_creep"):
            for k, v in doc.items():
                literature.setdefault(k, []).extend(v if isinstance(v, list) else [])
        elif isinstance(doc, list):
            recs.extend(doc)
        else:
            overlays.append(doc)
    recs = dedupe(recs)
    recs = apply_overlays(recs, overlays)
    ents = build_entries(recs, literature=literature)
    write_db(ents, a.out)
    print(f"{len(ents)} entries -> {a.out}")


if __name__ == "__main__":
    main()
