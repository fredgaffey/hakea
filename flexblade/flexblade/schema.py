"""Design and result schema — the contract shared by every flexblade module.

All quantities SI unless the field name ends in _deg or _in. Frames: see DESIGN.md.
"""
from __future__ import annotations

import hashlib
import json
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, model_validator

MODEL_VERSION = "0.1.0"

Vec3 = tuple[float, float, float]


class _M(BaseModel):
    model_config = ConfigDict(extra="forbid")


# --------------------------------------------------------------------------- materials / print


class PrintOrientation(_M):
    """Print frame of a part, expressed in hub frame H.

    build_dir: layer-stacking direction (material axis 3, weakest).
    raster_dir: dominant road/fibre direction (material axis 1). Must be ⟂ build_dir
    (it is orthogonalised if not).
    """
    build_dir: Vec3 = (0.0, 0.0, 1.0)
    raster_dir: Vec3 = (1.0, 0.0, 0.0)


class Layup(_M):
    """Cross-section material arrangement.

    solid:     whole section of `material`.
    core_skin: `material` core with `skin_material` shell of `skin_thickness`.
    rod_insert: `material` base with circular rods of `insert_material`,
                `insert_diameter`, placed at chord fractions `insert_positions`
                (from leading edge) on the section mid-line.
    """
    kind: Literal["solid", "core_skin", "rod_insert"] = "solid"
    material: str = "tpu_64d"
    skin_material: Optional[str] = None
    skin_thickness: float = 0.0
    insert_material: Optional[str] = None
    insert_diameter: float = 0.0
    insert_positions: list[float] = Field(default_factory=list)


# --------------------------------------------------------------------------- blade


class Airfoil(_M):
    kind: Literal["naca4", "coords"] = "naca4"
    naca: str = "4412"
    # for kind == coords: closed loop x/c, y/c from TE over upper surface to LE to TE
    coords: Optional[list[tuple[float, float]]] = None


class BladeStation(_M):
    r_frac: float = Field(ge=0.0, le=1.0, description="r / R")
    chord: float = Field(gt=0, description="m")
    twist_deg: float = Field(description="geometric pitch at zero collective, deg")
    thickness_frac: Optional[float] = Field(
        None, description="t/c override; None = airfoil's own")
    layup: Optional[Layup] = Field(None, description="None = blade default layup")


class Blade(_M):
    diameter_in: float = Field(5.0, ge=3.0, le=14.0)
    n_blades: int = Field(2, ge=1, le=6)
    root_cutout_frac: float = Field(
        0.18, description="r/R where aerodynamic blade starts (end of flexure/hub)")
    airfoil: Airfoil = Airfoil()
    stations: list[BladeStation] = Field(
        default_factory=list,
        description="spanwise definition, r_frac ascending; empty = preset law")
    layup: Layup = Layup()
    orientation: PrintOrientation = PrintOrientation()
    elastic_axis_chord_frac: float = Field(
        0.25, description="beam reference line position along chord from LE")

    @property
    def radius(self) -> float:
        return self.diameter_in * 0.0254 / 2.0


# --------------------------------------------------------------------------- flexure (FACT)


class FlexureMember(_M):
    """One compliant member (generated by fact.py or user-given).

    Endpoints in frame H of blade 1 (blade 2.. generated by rotation + skew mirror).
    kind wire: slender beam, cross-section width×thickness (≈ square/circle).
    kind blade: thin wide plate flexure; `width_dir` gives the plate's wide direction.
    """
    kind: Literal["wire", "blade", "rigid"] = "blade"
    p0: Vec3
    p1: Vec3
    width: float = Field(gt=0)
    thickness: float = Field(gt=0)
    width_dir: Vec3 = (0.0, 0.0, 1.0)
    shape: Literal["rect", "circle"] = "rect"
    taper: float = Field(1.0, description="thickness at p1 / thickness at p0")
    layup: Layup = Layup()
    orientation: PrintOrientation = PrintOrientation()


class TopoptFlexure(_M):
    """Stored result of a topology-optimised flexure (flexblade.topopt), used by
    topology == "topopt": rotor.py replaces the flexure by a zero-length 6×6 spring at
    the hinge point plus a lumped mass, so evaluate() runs the 1/rev analysis on it."""
    K6: list[list[float]] = Field(description="6×6 stiffness at the hinge point, blade-1 frame H, "
                                              "[ux,uy,uz,rx,ry,rz] → [Fx,Fy,Fz,Mx,My,Mz], rpm 0")
    mass: float = Field(0.0, description="kg, designed flexure region")
    com: Vec3 = (0.0, 0.0, 0.0)
    inertia: list[list[float]] = Field(default_factory=lambda: [[0.0] * 3 for _ in range(3)],
                                       description="kg m², about the COM, frame H")
    source: str = Field("", description="result directory / file the data came from")
    parts: list[dict] = Field(default_factory=list,
                              description="smoothed per-material surfaces for the viewer: "
                                          "{name, material, stl} (blade-1 frame H, STL in mm; a "
                                          "relative stl path is relative to `source`)")
    notes: str = ""


class Flexure(_M):
    """Root compliance between hub and aerodynamic blade.

    topology:
      skewed_cross_blade  two crossed blade flexures whose intersection line is the
                          virtual lag hinge, skewed by skew_deg (FACT: 1 rotational DOF)
      skewed_cross_blade_sym  as skewed_cross_blade, but one set is split into two outer
                          half-width plates either side of the other (symmetric "butterfly"
                          cross-spring): no parasitic couple from the centrifugal load
      skewed_single_blade one thin blade flexure whose bending axis is skewed
      wire_triplet        3+ wire flexures whose lines intersect the hinge axis
                          (FACT constraint lines ⟂-free set) + optional tension member
      integral_taper      no separate flexure: blade root section thinned/tapered and
                          bend-twist coupled by skewed root geometry (monolithic TPU)
      torsion_bar         stiff bar lying ON the skewed hinge axis (one end gripped by the hub,
                          the other by the blade): constrains 5 DOF, the hinge motion is the
                          bar's own torsion. Optional TPU plate around it (`thickness` > 0,
                          `layup`) tunes stiffness/damping. Bar: bar_diameter, bar_material,
                          bar_length (None = `length`). Needs a thick hub block, not a thin root.
      custom              use `members` as given
      rigid               rigid root (reference / baseline)
      topopt              topology-optimised flexure: `topopt` holds its 6×6 stiffness and
                          mass properties (flexblade topopt); `members` are only drawn
    """
    topology: Literal["skewed_cross_blade", "skewed_cross_blade_sym", "skewed_single_blade",
                      "wire_triplet", "integral_taper", "torsion_bar", "custom",
                      "rigid", "topopt"] = "skewed_cross_blade"
    skew_deg: float = Field(45.0, description="hinge axis tilt from rotor axis toward span, "
                                              "blade 1 +, blade 2 mirrored to −")
    hinge_radius: float = Field(0.012, description="radial position of virtual hinge axis, m")
    length: float = Field(0.008, description="flexure active length, m")
    thickness: float = Field(0.0012, description="member thickness, m")
    width: float = Field(0.008, description="member width, m")
    cross_angle_deg: float = Field(90.0, description="angle between crossed blades")
    bar_diameter: float = Field(0.0015, gt=0, description="torsion_bar: bar diameter, m")
    bar_material: str = Field("cf_rod_pultruded", description="torsion_bar: bar material "
                              "(pultruded CF: G/E ≈ 0.04 → soft in torsion, stiff in bending)")
    bar_length: Optional[float] = Field(None, description="torsion_bar: bar length along the "
                                        "hinge axis, m; None = `length`")
    bar_with_plate: bool = Field(True, description="torsion_bar: add the TPU plate (layup, "
                                 "thickness, width) around the bar")
    cross_gap: float = Field(0.001, ge=0.0, description="axial gap between the two crossed plates "
                             "along the hinge axis, m; must exceed ~2 nozzle widths or the plates "
                             "fuse when printed (FEA: fused cross is ~1.9x stiffer)")
    taper: float = 1.0
    twist_deg: float = Field(0.0, description="pre-twist of members about their axis")
    layup: Layup = Layup()
    orientation: PrintOrientation = PrintOrientation()
    tension_member: Optional[FlexureMember] = Field(
        None, description="optional radial strap/rod carrying centrifugal load")
    tension_rod_diameter: float = Field(
        0.0, ge=0.0, description="m; > 0 adds a radial rod (wire member) on the rotor-plane line "
                                 "through the hinge point, hub radius → blade end of the flexure, "
                                 "carrying the centrifugal load (split load path; FACT-compatible: "
                                 "the line intersects the hinge axis). 0 = none")
    tension_rod_material: str = Field("cf_rod_pultruded", description="material of the tension rod")
    members: list[FlexureMember] = Field(
        default_factory=list, description="explicit members (custom) or fact.py output")
    hub_radius: float = Field(0.006, description="rigid hub outer radius, m")
    topopt: Optional[TopoptFlexure] = Field(None, description="topology == topopt: stored result")


# --------------------------------------------------------------------------- operating point / motor


class Motor(_M):
    name: str = "tmotor_2307_1300kv"
    kv: float = 1380.0            # rpm/V (fitted effective)
    R: float = 0.158              # ohm phase-phase-equivalent
    J_rotor: float = 4.17e-6      # kg m^2 motor bell
    J_hub: float = 2.0e-6         # kg m^2 hub + fasteners (excluding blades)
    supply_V: float = 24.0
    max_current: float = 40.0
    torque_bandwidth_hz: float = 2000.0  # ESC/encoder current-loop bandwidth estimate
    # --- averaged BLDC + AM32 model (scripts/motorid fit, notes/motorid/motor_model.json)
    L: float = Field(3.6e-5, description="phase-phase inductance, H. Best estimate (±30 %) from "
                                         "motor scaling (motor.estimate_L), not bench-identified "
                                         "(sweeps <50 Hz). Dominates 1/rev torque phase.")
    Rb: float = Field(0.043, description="battery + lead resistance, ohm")
    b: float = Field(7.4e-6, description="viscous friction, N m s/rad")
    T0: float = Field(1.3e-6, description="Coulomb friction, N m")
    voltage_gain: float = Field(1.04, description="AM32 effective duty->voltage gain g(rpm)")
    poles: int = 14
    thermal_resistance_KW: float = Field(3.0, description="winding->ambient thermal resistance with "
                                         "prop wash, K/W. Guess for 2307 class (+-50 %); library "
                                         "motors scale ~ 1/stator area (d*h)")
    max_winding_C: float = Field(120.0, description="max continuous winding temperature, C "
                                 "(enamel class ~130-155 C, magnets N-grade ~80-150 C; guess)")
    duty_slew_max: float = Field(160.0, description="AM32 max duty change per second (fraction/s); "
                                                    "max_ramp 16 per 50 us tick of 2000 -> 160/s")


class OperatingPoint(_M):
    vehicle_mass: float = Field(0.6, description="kg; hover thrust = m g")
    rpm: Optional[float] = Field(None, description="None = trim rpm to hover thrust")
    collective_deg: float = Field(0.0, description="added to blade twist")
    torque_mod_frac: float = Field(0.3, description="1/rev torque amplitude / mean torque. For "
                                   "drive='duty' this sets the duty amplitude giving this torque "
                                   "ratio at locked speed and DC; delivered torque is lower/lagged")
    drive: Literal["duty", "torque"] = Field(
        "duty", description="duty: ESC modulates duty, torque via motor R-L + back-EMF model; "
                            "torque: ideal torque source on hub")
    duty_mod_amp: Optional[float] = Field(None, description="explicit 1/rev duty amplitude "
                                          "(fraction); overrides torque_mod_frac when drive='duty'")
    rho: float = 1.225
    temperature_C: float = 25.0
    rpm_grid: list[float] = Field(default_factory=list,
                                  description="Campbell rpm grid; empty = auto")
    thrust_share: Optional[float] = Field(
        None, description="fraction of vehicle weight this rotor carries (set by coaxial trim); "
                          "None = 1")
    extra_inflow: Optional[InflowProfile] = Field(
        None, description="imposed by the other rotor in a coaxial pair; set by coaxial.py")


class AnalysisOptions(_M):
    n_blade_elements: int = 16
    n_flexure_elements: int = 6
    aero: Literal["none", "quasi_steady", "theodorsen"] = "theodorsen"
    dynamic_inflow: bool = True
    coriolis: bool = True
    nonlinear_static: bool = True
    n_modes: int = 8
    fatigue_cycles: float = 1.0e7


class InflowProfile(_M):
    """Extra axial inflow imposed on a rotor by another rotor (coaxial interference).

    v(r) = interp(r_frac, v) in m/s, positive DOWN, added to the rotor's own induced
    velocity in aero.trim (and hence everywhere downstream)."""
    r_frac: list[float] = Field(default_factory=list)
    v: list[float] = Field(default_factory=list)


class Coaxial(_M):
    """Second, counter-rotating rotor below the primary (primary = upper, spins +Ω about +z).

    The lower rotor spins −Ω. It is analysed in its own mirrored frame with the same code;
    outputs are mirrored back (phase sign flips). Each rotor has its own motor, so cyclic
    can be pulsed on both and yaw comes from the torque difference.
    Fields left None copy the upper rotor's definition.
    """
    spacing_frac: float = Field(0.25, ge=0.05, le=2.0, description="axial spacing / R")
    lower_blade: Optional["Blade"] = None
    lower_flexure: Optional["Flexure"] = None
    lower_motor: Optional["Motor"] = None
    lower_collective_offset_deg: float = 0.0
    trim: Literal["torque_balance", "equal_rpm", "fixed_rpm"] = Field(
        "torque_balance", description="torque_balance: zero net yaw torque at hover thrust; "
                                      "equal_rpm: same rpm both; fixed_rpm: op.rpm upper, lower_rpm")
    lower_rpm: Optional[float] = None
    lower_torque_mod_frac: Optional[float] = Field(None, description="None = same as upper")
    pulse_phase_offset_deg: float = Field(
        0.0, description="lower rotor 1/rev pulse azimuth relative to upper, chosen so control "
                         "moments add; 0 = aligned for maximum combined moment")


class FormOp(_M):
    """Post-print heat-forming of one region (rigid-rotation first model: the region's final
    PrintOrientation = R_form · as-printed). Ops of a region compose in list order.

    twist: rotate about `axis` (frame H, through the region) by angle_deg.
    bend:  bend about the line direction `axis` by angle_deg at `radius` (m).
    inserts_in_unbent: bend only — pultruded/steel inserts sit in an unbent segment (user
      asserts the bend line misses them); otherwise an insert must be parallel to the bend line.
    """
    region: Literal["blade", "flexure"] = "flexure"
    kind: Literal["twist", "bend"] = "twist"
    axis: Vec3 = (1.0, 0.0, 0.0)
    angle_deg: float = 0.0
    radius: float = Field(0.006, gt=0, description="bend radius, m")
    inserts_in_unbent: bool = False


class PrintSetup(_M):
    """One build direction for the WHOLE multi-material print (frame H) plus per-region
    in-layer raster angles; `printsetup.apply_print_setup` derives every part's
    PrintOrientation from it.

    build_dir: layer-stacking direction; None -> take it from `preset`
      flat (z, rotor axis) | on_edge (y, chordwise) | hinge_in_plane (build ⟂ hinge axis,
      rotated about it to minimise flexure overhang) | tilted (build_dir from tilt_deg/azimuth_deg: continuous variable) |
      formed_torsion_bar (build z, flexure
      printed flat then heat-formed so the bar ends on the skewed hinge axis).
    blade_raster_deg / flexure_raster_deg: in-layer raster angle about build_dir, from the
      projection of the blade span (+x) into the layer plane (right-handed about build_dir).
      Inserts (rods, bar, tension member) always have their fibre axis along the insert.
    pauses: insert names dropped in at a print pause: "bar", "tension_rod", "tension_member",
      "rod_insert", "member<i>".
    """
    preset: Literal["flat", "on_edge", "hinge_in_plane", "formed_torsion_bar", "drilled_torsion_bar",
                    "tilted"] = "flat"
    tilt_deg: float = Field(0.0, description="preset tilted: build_dir tilt from the rotor axis z, deg")
    azimuth_deg: float = Field(0.0, description="preset tilted: azimuth of the tilt about z from +x, deg")
    install: dict[str, Literal["pause", "drilled"]] = Field(
        default_factory=dict, description="per insert ('bar','rod_insert','tension_rod',"
        "'tension_member','member<i>'): laid in at a print pause (must lie in a layer) or drilled "
        "after printing/forming. Default: bar drilled, others pause. formed_torsion_bar: bar pause "
        "(rod = forming mandrel)")
    build_dir: Optional[Vec3] = None
    blade_raster_deg: float = 0.0
    flexure_raster_deg: float = 0.0
    pauses: list[str] = Field(default_factory=list)
    form: list[FormOp] = Field(default_factory=list, description="post-print heat-forming; the "
                               "as-printed state is build_dir, the final = form applied. Preset "
                               "formed_torsion_bar fills it (flat print, bar in-plane, twist 90° "
                               "about the bar, bend (90°−skew) about y) if empty")


class Design(_M):
    name: str = "unnamed"
    layout: Literal["single", "coaxial"] = "single"
    coaxial: Coaxial = Coaxial()
    blade: Blade = Blade()
    flexure: Flexure = Flexure()
    motor: Motor = Motor()
    op: OperatingPoint = OperatingPoint()
    analysis: AnalysisOptions = AnalysisOptions()
    print_setup: Optional[PrintSetup] = Field(
        None, description="single build direction + region raster angles; None = per-part "
                          "blade/flexure.orientation as given")
    notes: str = ""

    def canonical_json(self) -> str:
        return json.dumps(self.model_dump(mode="json"), sort_keys=True, separators=(",", ":"))

    def hash(self) -> str:
        return hashlib.sha256(self.canonical_json().encode()).hexdigest()[:16]


