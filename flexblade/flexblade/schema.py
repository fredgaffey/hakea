from pydantic import BaseModel, ConfigDict, Field, model_validator

MODEL_VERSION = "0.1.0"

Vec3 = tuple[float, float, float]


class _M(BaseModel):
    model_config = ConfigDict(extra="forbid")


# --------------------------------------------------------------------------- materials / print


class PrintOrientation(_M):
    """Print frame of a part, expressed in hub frame H.

    build_dir: layer-stacking direction (material axis 3, weakest).
    raster_dir: dominant road/fibre direction (material axis 1). Must be ⟂ build_dir
    (it is orthogonalised if not).
    """
    build_dir: Vec3 = (0.0, 0.0, 1.0)
    raster_dir: Vec3 = (1.0, 0.0, 0.0)


class Layup(_M):
    """Cross-section material arrangement.

    solid:     whole section of `material`.
    core_skin: `material` core with `skin_material` shell of `skin_thickness`.
    rod_insert: `material` base with circular rods of `insert_material`,
                `insert_diameter`, placed at chord fractions `insert_positions`
                (from leading edge) on the section mid-line.
    """
    kind: Literal["solid", "core_skin", "rod_insert"] = "solid"
    material: str = "tpu_64d"
    skin_material: Optional[str] = None
    skin_thickness: float = 0.0
    insert_material: Optional[str] = None
    insert_diameter: float = 0.0
    insert_positions: list[float] = Field(default_factory=list)


# --------------------------------------------------------------------------- blade


class Airfoil(_M):
    kind: Literal["naca4", "coords"] = "naca4"
    naca: str = "4412"
    # for kind == coords: closed loop x/c, y/c from TE over upper surface to LE to TE
    coords: Optional[list[tuple[float, float]]] = None


class BladeStation(_M):
    r_frac: float = Field(ge=0.0, le=1.0, description="r / R")
    chord: float = Field(gt=0, description="m")
    twist_deg: float = Field(description="geometric pitch at zero collective, deg")
    thickness_frac: Optional[float] = Field(
        None, description="t/c override; None = airfoil's own")
    layup: Optional[Layup] = Field(None, description="None = blade default layup")


class BalanceMass(_M):
    """Point balance mass fixed in the blade (e.g. a steel pin pressed into the root): mass
    `mass` at radius r_frac·R, offset in the blade section frame from the reference line
    (elastic axis): `chord_offset` toward the LE (+), `normal_offset` along the section normal
    (+ = suction/thrust side). A pair at ±normal_offset is a "Chinese weight" (tennis-racket
    balance): it gives I_normal > I_chord, opposing the centrifugal propeller moment."""
    mass: float = Field(0.0, ge=0.0, description="kg")
    r_frac: float = Field(0.25, ge=0.0, le=1.0)
    chord_offset: float = 0.0
    normal_offset: float = 0.0


class Blade(_M):
    diameter_in: float = Field(5.0, ge=3.0, le=14.0)
    n_blades: int = Field(2, ge=1, le=6)
    root_cutout_frac: float = Field(
        0.18, description="r/R where aerodynamic blade starts (end of flexure/hub)")
    airfoil: Airfoil = Airfoil()
    stations: list[BladeStation] = Field(
        default_factory=list,
        description="spanwise definition, r_frac ascending; empty = preset law")
    layup: Layup = Layup()
    orientation: PrintOrientation = PrintOrientation()
    elastic_axis_chord_frac: float = Field(
        0.25, description="beam reference line position along chord from LE")
    balance_masses: list[BalanceMass] = Field(
        default_factory=list, description="point masses in the blade (CF propeller-moment balance)")

    @property
    def radius(self) -> float:
        return self.diameter_in * 0.0254 / 2.0


# --------------------------------------------------------------------------- flexure (FACT)


class FlexureMember(_M):
    """One compliant member (generated by fact.py or user-given).

    Endpoints in frame H of blade 1 (blade 2.. generated by rotation + skew mirror).
    kind wire: slender beam, cross-section width×thickness (≈ square/circle).
    kind blade: thin wide plate flexure; `width_dir` gives the plate's wide direction.
    """
    kind: Literal["wire", "blade", "rigid"] = "blade"
    p0: Vec3
    p1: Vec3
    width: float = Field(gt=0)
    thickness: float = Field(gt=0)
    width_dir: Vec3 = (0.0, 0.0, 1.0)
    shape: Literal["rect", "circle"] = "rect"
    taper: float = Field(1.0, description="thickness at p1 / thickness at p0")
    layup: Layup = Layup()
    orientation: PrintOrientation = PrintOrientation()
    anchorage: Literal["butt", "embedded"] = Field(
        "butt", description="end condition on the fittings: butt = member ends flush on the "
        "fitting face (anchorage.py punch springs); embedded = member continuous into / bonded "
        "over a length inside the fitting (printed monolithic with fillets, or rod bonded in a "
        "blind hole ≥ 3 d deep): no contact interface, ends treated as rigidly joined")
    cable: bool = Field(False, description="unbonded strand (tension-torsion strap): axial "
                        "stiffness of the fibre area, bending/torsion scaled by cable_bend_factor; "
                        "hinge stiffness then comes from the tension (geometric stiffness)")
    cable_bend_factor: float = Field(1e-3, gt=0.0, description="EI, GJ multiplier of a cable "
                                     "member vs the solid fibre-equivalent rod (≈ 1/filaments)")


class TopoptFlexure(_M):
    """Stored result of a topology-optimised flexure (flexblade.topopt), used by
    topology == "topopt": rotor.py replaces the flexure by a zero-length 6×6 spring at
    the hinge point plus a lumped mass, so evaluate() runs the 1/rev analysis on it."""
    K6: list[list[float]] = Field(description="6×6 stiffness at the hinge point, blade-1 frame H, "
                                              "[ux,uy,uz,rx,ry,rz] → [Fx,Fy,Fz,Mx,My,Mz], rpm 0")
    mass: float = Field(0.0, description="kg, designed flexure region")
    com: Vec3 = (0.0, 0.0, 0.0)
    inertia: list[list[float]] = Field(default_factory=lambda: [[0.0] * 3 for _ in range(3)],
                                       description="kg m², about the COM, frame H")
    source: str = Field("", description="result directory / file the data came from")
    parts: list[dict] = Field(default_factory=list,
                              description="smoothed per-material surfaces for the viewer: "
                                          "{name, material, stl} (blade-1 frame H, STL in mm; a "
                                          "relative stl path is relative to `source`)")
    notes: str = ""


class IdealFlexure(_M):
    """topology == "ideal": material-free generalised root spring ("idealise then realise").
    Zero-length 6×6 spring at the hinge point H0 (blade-1 frame H: x radial, y in-plane /
    chordwise, z rotor axis), plus blade mass-placement knobs. Rotations: principal stiffnesses
    about the skewed hinge axis a = (sin s, 0, −cos s) (s = flexure.skew_deg), about
    b = a × y (the complementary skewed axis in the x–z plane) and about y (flap). Lag (z) and
    pitch (x) are therefore coupled through the skew. Translations: axial x, in-plane y,
    out-of-plane z. `K6` (if given) overrides all stiffness parameters (any flexure's K).
    No material: strain / creep / fatigue checks do not apply."""
    k_hinge: float = Field(0.05, gt=0, description="N m/rad about the skewed hinge axis a")
    k_cross: float = Field(20.0, gt=0, description="N m/rad about b = a × y")
    k_flap: float = Field(20.0, gt=0, description="N m/rad about y (flap)")
    k_axial: float = Field(1e6, gt=0, description="N/m radial (x)")
    k_inplane: float = Field(1e6, gt=0, description="N/m in-plane / chordwise (y)")
    k_outplane: float = Field(1e6, gt=0, description="N/m out-of-plane (z)")
    K6: Optional[list[list[float]]] = Field(None, description="explicit 6×6 at H0, frame H, "
                                            "[ux,uy,uz,rx,ry,rz] → [F;M]; overrides the k_*")
    loss_eta: float = Field(0.0, ge=0.0, description="hysteretic loss factor of the spring")
    mass: float = Field(0.0, ge=0.0, description="kg lumped at the hinge point (blade side)")
    lag_inertia: float = Field(0.0, ge=0.0, description="kg m² extra about z at the hinge "
                               "point (blade side), e.g. a lag-tuning mass")
    tip_mass: float = Field(0.0, ge=0.0, description="kg point mass at the blade tip")
    tip_mass_chord: float = Field(0.0, description="m, tip mass offset along +y (frame H) "
                                  "from the elastic axis")


class Flexure(_M):
    """Root compliance between hub and aerodynamic blade.

    topology:
      skewed_cross_blade  two crossed blade flexures whose intersection line is the
                          virtual lag hinge, skewed by skew_deg (FACT: 1 rotational DOF)
      skewed_cross_blade_sym  as skewed_cross_blade, but one set is split into two outer
                          half-width plates either side of the other (symmetric "butterfly"
                          cross-spring): no parasitic couple from the centrifugal load
      skewed_single_blade one thin blade flexure whose bending axis is skewed
      wire_triplet        3+ wire flexures whose lines intersect the hinge axis
                          (FACT constraint lines ⟂-free set) + optional tension member
      integral_taper      no separate flexure: blade root section thinned/tapered and
                          bend-twist coupled by skewed root geometry (monolithic TPU)
      torsion_bar         stiff bar lying ON the skewed hinge axis (one end gripped by the hub,
                          the other by the blade): constrains 5 DOF, the hinge motion is the
                          bar's own torsion. Optional TPU plate around it (`thickness` > 0,
                          `layup`) tunes stiffness/damping. Bar: bar_diameter, bar_material,
                          bar_length (None = `length`). Needs a thick hub block, not a thin root.
      skewed_cruciform    X-section torsion hinge: two thin plates (width `width`, thickness
                          `thickness`, length `bar_length` or `length`) whose LENGTH lies on the
                          skewed hinge axis, crossing on it at cross_angle_deg. Hinge = torsion
                          of the open section (∝ b t³, warping-free since all arms meet at one
                          point), cross/flap = plate bending (∝ t b³), CF = axial. Optional
                          centroid CF rod (cruciform_rod_diameter, bar_material). Ends embedded
                          (printed continuous into hub and blade fittings).
      custom              use `members` as given
      rigid               rigid root (reference / baseline)
      topopt              topology-optimised flexure: `topopt` holds its 6×6 stiffness and
                          mass properties (flexblade topopt); `members` are only drawn
      ideal               material-free generalised 6×6 spring + mass knobs (`ideal`,
                          IdealFlexure): the target a real flexure should approximate
    """
    topology: Literal["skewed_cross_blade", "skewed_cross_blade_sym", "skewed_single_blade",
                      "wire_triplet", "integral_taper", "torsion_bar", "skewed_cruciform", "custom",
                      "rigid", "topopt", "ideal"] = "skewed_cross_blade"
    skew_deg: float = Field(45.0, description="hinge axis tilt from rotor axis toward span, "
                                              "blade 1 +, blade 2 mirrored to −")
    hinge_radius: float = Field(0.012, description="radial position of virtual hinge axis, m")
    pre_lag_deg: float | Literal["auto"] = Field(
        0.0, description="built-in rotation of the blade-side geometry (fitting + blade) about "
        "each blade's own (mirrored) skewed hinge axis relative to the unstressed flexure, deg, "
        "lag-positive: both blades get the same lag, opposite pitch. 'auto' = solved at the "
        "reference op (pre_lag_ref_mass) so the trimmed hover blade-1 vs blade-2 pitch split "
        "(elastic + preset) is zero")
    pre_lag_axis: Literal["hinge", "pitch"] = Field(
        "hinge", description="pre_lag_deg rotates the blade side about the skewed hinge axis "
        "(lag + pitch; the centrifugal pendulum restores most of it when k_hinge << K_cf) or "
        "'pitch': only its pitch component (preset blade pitch about the span axis, ±ψ·sin s "
        "per blade, no lag/CG shift) — cancels a throttle-invariant split directly")
    pre_lag_ref_mass: Optional[float] = Field(
        None, description="pre_lag_deg='auto': vehicle mass of the op it is solved at, kg "
        "(None = op.vehicle_mass); robust variants pin it to the nominal mass")
    length: float = Field(0.008, description="flexure active length, m")
    thickness: float = Field(0.0012, description="member thickness, m")
    width: float = Field(0.008, description="member width, m")
    cross_angle_deg: float = Field(90.0, description="angle between crossed blades")
    bar_diameter: float = Field(0.0015, gt=0, description="torsion_bar: bar diameter, m")
    bar_material: str = Field("cf_rod_pultruded", description="torsion_bar: bar material "
                              "(pultruded CF: G/E ≈ 0.04 → soft in torsion, stiff in bending)")
    bar_length: Optional[float] = Field(None, description="torsion_bar: bar length along the "
                                        "hinge axis, m; None = `length`")
    bar_with_plate: bool = Field(True, description="torsion_bar: add the TPU plate (layup, "
                                 "thickness, width) around the bar")
    cruciform_rod_diameter: float = Field(0.0, ge=0.0, description="skewed_cruciform: CF rod "
                                          "along the section centroid (on the hinge axis), m; 0 = none")
    cross_gap: float = Field(0.001, ge=0.0, description="axial gap between the two crossed plates "
                             "along the hinge axis, m; must exceed ~2 nozzle widths or the plates "
                             "fuse when printed (FEA: fused cross is ~1.9x stiffer)")
    strip_clamp: Literal["sharp", "radiused", "compliant"] = Field(
        "radiused", description="clamp-edge model for steel shim strips (fatigue Kt/fretting): "
        "sharp square jaw, radiused jaw (strip_clamp_radius), or compliant TPU/soft pad lip")
    strip_laminae: int = Field(1, ge=1, le=8, description="steel shim strips: number of "
                               "unbonded laminae per strip (each `thickness` thick, clamped "
                               "together at both ends, free to slide between): bending about "
                               "the thin axis n*E*w*t^3/12, axial / in-plane / torsion / mass x n, "
                               "fatigue strain at the lamina thickness (laminate.py)")
    strip_lam_eta: float = Field(0.0, ge=0.0, description="equivalent loss factor (2*zeta_eq) of "
                                 "interlaminar Coulomb friction at the clamp ends, added to the "
                                 "strip elements' complex stiffness (laminate.friction_eta at the "
                                 "operating 1P amplitude); 0 = none")
    strip_clamp_radius: float = Field(0.0, ge=0.0, description="m, jaw radius for 'radiused'; "
                                      "0 = auto 10x strip thickness")
    fitting_mass: Literal["auto", "none"] = Field(
        "auto", description="clamped steel strips (steelx): 'auto' lumps the CSG hub/root fitting "
        "mass + inertia (fittings.py) into the beam model; 'none' = legacy (shank only)")
    fitting_slim: bool = Field(False, description="slim steelx fittings: stepped jaws (1.5 mm "
                               "faces past the exit radius), 2 mm web, no filler between the jaws "
                               "(walls >= 1.2 mm, clamp lands kept)")
    fitting_balance_mass: Union[float, Literal["auto"]] = Field(
        0.0, description="kg per pin: a pair of balance pins (e.g. tungsten) pressed along the rotor "
        "axis into the blade-side (root) fitting at (x_cg, 0, +-fitting_balance_z) about the pitch "
        "axis; their normal spread cancels the fitting's chordwise propeller moment (I25). 'auto' = "
        "exact cancellation, fittings.balance_pin_mass")
    fitting_balance_z: float = Field(0.008, gt=0.0, description="m, balance pin offset along the "
                                     "rotor axis from the pitch axis")
    fitting_material: Optional[str] = Field(None, description="printed fitting material for "
                                            "the mass model; None = hub pa6_cf, root = blade layup")
    taper: float = 1.0
    twist_deg: float = Field(0.0, description="pre-twist of members about their axis")
    layup: Layup = Layup()
    orientation: PrintOrientation = PrintOrientation()
    tension_member: Optional[FlexureMember] = Field(
        None, description="optional radial strap/rod carrying centrifugal load")
    tension_rod_diameter: float = Field(
        0.0, ge=0.0, description="m; > 0 adds a radial rod (wire member) on the rotor-plane line "
                                 "through the hinge point, hub radius → blade end of the flexure, "
                                 "carrying the centrifugal load (split load path; FACT-compatible: "
                                 "the line intersects the hinge axis). 0 = none")
    tension_rod_material: str = Field("cf_rod_pultruded", description="material of the tension rod")
    # ---- tension-torsion strap (fact.py appends cable members; rotor.py checks the anchors)
    strap_strands: int = Field(0, ge=0, description="number of unbonded strands in the radial "
                               "tension-torsion strap carrying the centrifugal load; 0 = none")
    strap_strand_diameter: float = Field(0.0005, gt=0.0, description="m, fibre-area-equivalent "
                                         "solid diameter of one strand")
    strap_radius: float = Field(0.0, ge=0.0, description="m, radius of the circle the strands sit "
                                "on about the radial line through the hinge point (trapeze arm)")
    strap_material: str = Field("aramid_yarn", description="aramid_yarn | uhmwpe_braid | cf_tow")
    strap_length: float = Field(0.0, ge=0.0, description="m, free strand length centred on the "
                                "hinge point; 0 = hub radius → blade end of the flexure")
    strap_bend_factor: float = Field(1e-3, gt=0.0, description="strand EI/GJ vs solid rod")
    strap_anchor: Literal["pin_wrap", "knot", "epoxy_pot"] = Field(
        "pin_wrap", description="strand end anchorage: wrapped round a pin (loop), knotted, or "
        "potted in epoxy")
    strap_pin_diameter: float = Field(0.003, gt=0.0, description="m, pin for pin_wrap")
    strap_pot_length: float = Field(0.006, gt=0.0, description="m, bonded length for epoxy_pot")
    axial_release: bool = Field(False, description="printed flexure members get a radial slider "
                                "at the blade end so the strap carries the centrifugal load")
    axial_release_stiffness: float = Field(0.0, ge=0.0, description="N/m radial stiffness of the "
                                           "release (0 = free slider; > 0 = zig-zag spring)")
    members: list[FlexureMember] = Field(
        default_factory=list, description="explicit members (custom) or fact.py output")
    hub_radius: float = Field(0.006, description="rigid hub outer radius, m")
    fairing: bool = Field(False, description="root hardware (fitting, flexure, strap, shank) is "
                          "faired: bluff-body Cd 0.4 instead of 1.1 in the root drag model")
    root_envelope_ratio: float = Field(2.0, gt=0.0, description="soft limit: max root hardware "
                                       "height / root airfoil thickness (root_envelope check)")
    topopt: Optional[TopoptFlexure] = Field(None, description="topology == topopt: stored result")
    ideal: Optional[IdealFlexure] = Field(None, description="topology == ideal: spring + masses "
                                          "(None = IdealFlexure defaults)")


