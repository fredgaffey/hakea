import zipfile, sys
src, ini, out = sys.argv[1:4]
cfg = "; generated by PrusaSlicer 2.9.4\n\n" + "".join("; " + l for l in open(ini) if " = " in l and not l.startswith("#"))
xml = ('<?xml version="1.0" encoding="utf-8"?>\n<custom_gcodes_per_print_z>\n'
       '<code print_z="10.6" type="1" extruder="1" color="" extra="PAUSE 1: insert strip in the 2 open slots (blade1 s0, blade2 s1)" gcode="M601"/>\n'
       '<code print_z="13" type="1" extruder="1" color="" extra="PAUSE 2: insert strip in the 2 open slots (blade1 s1, blade2 s0)" gcode="M601"/>\n'
       '<mode value="SingleExtruder"/>\n</custom_gcodes_per_print_z>\n')
with zipfile.ZipFile(src) as zi, zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zo:
    for it in zi.infolist():
        zo.writestr(it, zi.read(it.filename))
    zo.writestr("Metadata/Slic3r_PE.config", cfg)
    zo.writestr("Metadata/Prusa_Slicer_custom_gcode_per_print_z.xml", xml)
print("wrote", out)
